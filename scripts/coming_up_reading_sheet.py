"""Print the reading sheet for one city's neighborhood meeting schedule, as Markdown.

Every association of ``content/coming-up/<city>/neighborhood-schedule.yaml``
is listed with a tick box: its name and rule as transcribed, what the loader
made of the rule, the meeting type and the modes read from it, the place,
the call-in details, and the next dates the rule gives. A person reads each
line against the city's PDF saved beside the file and records that the
reading was made, as a ``checked`` entry in the YAML. The sheet names the
commit whose content it lists; content changed after that commit has not
been read.

    venv/bin/python scripts/coming_up_reading_sheet.py birmingham \
        > docs/runbooks/coming-up-reading-birmingham.md

Reads only the content directory, through the schedule's own loader; no
database. Pattern: scripts/how_it_works_reading_sheet.py.
"""

from __future__ import annotations

import calendar
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from docket.services.neighborhood_schedule import (
    SCHEDULE_FILE,
    Association,
    Schedule,
    load_schedule,
    occurrences,
)

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "coming-up"
NEXT_DATES = 3


def _content_commit(city_dir: Path) -> str:
    done = subprocess.run(
        ["git", "log", "-1", "--format=%h %cs", "--", str(city_dir)],
        cwd=ROOT, capture_output=True, text=True, check=True,
    )
    return done.stdout.strip()


def _today() -> date:
    return datetime.now(ZoneInfo("America/Chicago")).date()


def _clock(hhmm: str) -> str:
    """``"17:30"`` as ``5:30 p.m.``."""
    hour, minute = int(hhmm[:2]), hhmm[3:]
    half = "a.m." if hour < 12 else "p.m."
    return f"{hour % 12 or 12}:{minute} {half}"


def _day(on: date) -> str:
    return f"{calendar.day_name[on.weekday()]}, {calendar.month_name[on.month]} {on.day}, {on.year}"


def _and(words: list[str]) -> str:
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def _reading(association: Association) -> str:
    """What the loader made of the rule, or the reason it is given no dates."""
    if association.ordinal is None:
        return f"no dates. {association.undated_reason}"
    if association.months is None:
        months = "every month"
    else:
        months = "in " + _and([calendar.month_name[m] for m in association.months])
    time = _clock(association.time) if association.time else "no time"
    return f"{association.ordinal} {association.weekday.capitalize()}, {months}, {time}"


def _association_lines(association: Association, dates: list[date], today: date, year: int) -> list[str]:
    if association.ordinal is None:
        next_dates = "none, because the rule is given no dates"
    elif dates:
        next_dates = "; ".join(_day(on) for on in dates[:NEXT_DATES])
    else:
        next_dates = f"none left in {year} from {today.isoformat()}"
    return [
        f"- [ ] **{association.name}**: \"{association.rule_text}\"",
        f"  - Read as: {_reading(association)}",
        f"  - Type: \"{association.type_text}\", read as: {', '.join(association.modes) or 'no mode'}",
        f"  - Place: {association.place if association.place is not None else 'none'}",
        f"  - Call-in: {association.remote if association.remote is not None else 'none'}",
        f"  - Next dates: {next_dates}",
    ]


def sheet(slug: str, schedule: Schedule, commit: str, today: date) -> str:
    by_name: dict[str, list[date]] = {}
    for occurrence in occurrences(schedule, today, date(schedule.year, 12, 31)):
        by_name.setdefault(occurrence.association.name, []).append(occurrence.on)
    lines = [
        f"# Reading sheet: the neighborhood meeting schedule for {slug}",
        "",
        (
            f"Generated by `scripts/coming_up_reading_sheet.py {slug}` from `content/coming-up/{slug}/` "
            f"as of commit {commit}, on {today.isoformat()}."
        ),
        "",
        f"- Source: {schedule.title}",
        f"- Revised: {schedule.revised.isoformat()}",
        f"- Public address: {schedule.url}",
        f"- Saved copy: `content/coming-up/{slug}/{schedule.file}`, read {schedule.read.isoformat()}",
        f"- SHA-256 of the saved copy: `{schedule.sha256}`",
        f"- Year the rules are expanded over: {schedule.year}",
        "",
        (
            "Every line with a box is one row of the city's table. Open the saved copy (or the public address), "
            "find the row, and read the line and the five under it against it: the name and the rule in quotes "
            "are the city's cells as printed, misspellings included; \"Read as\" is what docket.pub computes "
            "dates from; the type in quotes is the city's cell and the modes are what was read from it; the "
            "place and the call-in details are the two parts of the city's information cell; the dates are the "
            f"next {NEXT_DATES} the rule gives in {schedule.year}, counted from the day this sheet was generated. "
            f"Tick the box, and correct `content/coming-up/{slug}/{SCHEDULE_FILE}` where a line is wrong "
            "(then regenerate this sheet). When every box is ticked, add an entry to the file's `checked` list "
            "with your name, the date, and how you read it, fill in the record at the foot, and commit. "
            "Content changed after the commit above has not been read."
        ),
        "",
        f"## The {len(schedule.associations)} associations",
        "",
    ]
    for association in schedule.associations:
        lines.extend(_association_lines(association, by_name.get(association.name, []), today, schedule.year))
    lines.extend([
        "",
        "## Record of the reading",
        "",
        "- Read by:",
        "- Date:",
        "- Corrections made (commits), or \"none\":",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    slug = argv[1]
    city_dir = CONTENT / slug
    if not (city_dir / SCHEDULE_FILE).is_file():
        print(f"no schedule file: {city_dir / SCHEDULE_FILE}", file=sys.stderr)
        return 1
    sys.stdout.write(sheet(slug, load_schedule(city_dir), _content_commit(city_dir), _today()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
