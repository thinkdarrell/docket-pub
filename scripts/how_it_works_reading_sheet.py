"""Print the reading sheet for one city's "How it works" content, as Markdown.

Every sentence the page shows (stop descriptions, rule statements, open
questions, journey notes and titles, journey stop texts and gaps) is listed
with a tick box, beside the quotation and source it rests on, so a person can
read each against its source and record that the reading was made (``D127`` in
``docs/DEBT.md``). The sheet names the commit whose content it lists; content
changed after that commit has not been read.

    venv/bin/python scripts/how_it_works_reading_sheet.py birmingham \
        > docs/runbooks/how-it-works-reading-birmingham.md

Reads only the content directory, through the page's own loader; no database.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from docket.services.how_it_works import (
    Explainer,
    Journey,
    JourneyStop,
    Rule,
    load_explainer,
)

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content" / "how-it-works"


def _one_line(text: str) -> str:
    return " ".join(text.split())


def _content_commit(city_dir: Path) -> str:
    done = subprocess.run(
        ["git", "log", "-1", "--format=%h %cs", "--", str(city_dir)],
        cwd=ROOT, capture_output=True, text=True, check=True,
    )
    return done.stdout.strip()


def _rule_lines(rule: Rule) -> list[str]:
    lines = [f"- [ ] {_one_line(rule.statement)}"]
    if rule.quote:
        lines.append(f"  - Quoted: \"{_one_line(rule.quote)}\"")
    source = f"`sources/{rule.source_file}`" if rule.source_file else "no saved copy; the quotation is not machine-checked"
    lines.append(f"  - {rule.citation}, {source}, {rule.url}")
    return lines


def _journey_stop_lines(number: int, stop: JourneyStop) -> list[str]:
    when = stop.date.isoformat() if stop.date else "no date"
    lines = [f"- [ ] Stop {number} ({', '.join(stop.stops)}; {when}; record: {stop.record}): {_one_line(stop.text)}"]
    if stop.gap:
        lines.append(f"  - [ ] Gap: {_one_line(stop.gap)}")
    if stop.quote:
        checked = f"`sources/{stop.source_file}`" if stop.source_file else "copied by hand, not machine-checked"
        lines.append(f"  - Quoted ({checked}): \"{_one_line(stop.quote)}\"")
    ids = []
    if stop.meeting_id is not None:
        ids.append(f"meeting {stop.meeting_id}")
    if stop.item_id is not None:
        ids.append(f"item {stop.item_id}")
    if stop.seconds is not None:
        ids.append(f"at {stop.seconds} s")
    if ids:
        lines.append(f"  - Rows: {', '.join(ids)}")
    if stop.document_url:
        lines.append(f"  - Document: {stop.document_label}, {stop.document_url}")
    return lines


def _journey_lines(journey: Journey) -> list[str]:
    lines = [
        f"### Journey: {journey.label} (`{journey.key}`)",
        "",
        f"- [ ] Note: {_one_line(journey.note)}",
        f"- [ ] Title: {_one_line(journey.title)}",
    ]
    for number, stop in enumerate(journey.stops, start=1):
        lines.extend(_journey_stop_lines(number, stop))
    lines.append("")
    return lines


def sheet(slug: str, explainer: Explainer, commit: str) -> str:
    lines = [
        f"# Reading sheet: the \"How it works\" page for {slug}",
        "",
        (
            f"Generated by `scripts/how_it_works_reading_sheet.py {slug}` from `content/how-it-works/{slug}/` "
            f"as of commit {commit}. Sources were read on {explainer.sources_read}; the saved copies and their "
            f"public addresses are in `content/how-it-works/{slug}/sources/README.md`."
        ),
        "",
        (
            "Every line with a box is a sentence the page shows. Read it against the quotation and the source "
            "under it, tick it, and correct the content file where it is wrong (then regenerate this sheet). "
            "When every box is ticked, fill in the record at the foot and commit; that closes `D127` in "
            "`docs/DEBT.md`. Content changed after the commit above has not been read."
        ),
        "",
        "## The path and its rules",
        "",
    ]
    for stop in explainer.stops:
        side = f", a side route of `{stop.side_route_of}`" if stop.side_route_of else ""
        lines.extend([f"### {stop.name} (`{stop.key}`{side})", "", f"- [ ] Description: {_one_line(stop.description)}"])
        for rule in stop.rules:
            lines.extend(_rule_lines(rule))
        lines.append("")
    lines.extend(["## Open questions", ""])
    for heading, body in explainer.open_questions:
        lines.append(f"- [ ] {_one_line(heading)}: {_one_line(body)}")
    lines.extend(["", "## Journeys", ""])
    for journey in explainer.journeys:
        lines.extend(_journey_lines(journey))
    lines.extend([
        "## Record of the reading",
        "",
        "- Read by:",
        "- Date:",
        "- Corrections made (commits), or \"none\":",
        "",
    ])
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    slug = argv[1]
    city_dir = CONTENT / slug
    if not city_dir.is_dir():
        print(f"no content directory: {city_dir}", file=sys.stderr)
        return 1
    sys.stdout.write(sheet(slug, load_explainer(city_dir), _content_commit(city_dir)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
